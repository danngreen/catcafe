export const GLYPH_W = 5;
export const GLYPH_H = 8;
export const LINE_H = 10;

const ORDER = Object.keys(G);
const INDEX = new Map(ORDER.map((ch, i) => [ch, i]));

// Per-colour baked strips: one row of glyphs, GLYPH_W apart.
const strips = new Map();

function stripFor(hex) {
  let s = strips.get(hex);
  if (s) return s;
  const buf = new PixBuf(ORDER.length * GLYPH_W, GLYPH_H);
  const packed = PixBuf.rgba(hex);
  ORDER.forEach((ch, i) => {
    const rows = G[ch];
    for (let y = 0; y < GLYPH_H; y++) {
      const row = rows[y] || '';
      for (let x = 0; x < GLYPH_W; x++) {
        if (row[x] === '#') buf.set(i * GLYPH_W + x, y, packed);
      }
    }
  });
  s = buf.toCanvas();
  strips.set(hex, s);
  return s;
}

/** Width in pixels of `text` at `scale`, accounting for 1px letter spacing. */
export function textWidth(text, scale = 1) {
  return text.length * (GLYPH_W + 1) * scale;
}

/**
 * Draw text. Returns the width drawn.
 * Options: { color, scale, shadow (hex|null) }
 */
export function drawText(ctx, text, x, y, opts = {}) {
  const { color = '#ffffff', scale = 1, shadow = null } = opts;
  const str = String(text);
  if (shadow) blit(ctx, str, x, y + scale, shadow, scale);
  blit(ctx, str, x, y, color, scale);
  return textWidth(str, scale);
}

function blit(ctx, str, x, y, color, scale) {
  const strip = stripFor(color);
  const step = (GLYPH_W + 1) * scale;
  for (let i = 0; i < str.length; i++) {
    const idx = INDEX.get(str[i]);
    if (idx === undefined || str[i] === ' ') continue;
    ctx.drawImage(
      strip, idx * GLYPH_W, 0, GLYPH_W, GLYPH_H,
      Math.round(x + i * step), Math.round(y), GLYPH_W * scale, GLYPH_H * scale,
    );
  }
}

/** Draw text centred on `cx`. */
export function drawTextCentered(ctx, text, cx, y, opts = {}) {
  const w = textWidth(String(text), opts.scale || 1);
  return drawText(ctx, text, Math.round(cx - w / 2), y, opts);
}

/** Draw text right-aligned so it ends at `rx`. */
export function drawTextRight(ctx, text, rx, y, opts = {}) {
  const w = textWidth(String(text), opts.scale || 1);
  return drawText(ctx, text, Math.round(rx - w), y, opts);
}
